# ⑤ **흐르되 바닥은 고정된** 전체화면 TUI — 씨앗 지어내기가 실제로 일어나는 화면 (T5, 2회차 G6).
#
# 왜 이 모양이어야 하나. 지어내기는 "꼬리 일치가 **부분적으로** 성공할 때" 난다:
# 화면의 마지막 몇 줄만 `recent` 의 꼬리와 맞으면 `historyAbove` 가 나머지 앞부분을 **과거로
# 돌려주는데**, 알트 판에는 그런 과거가 없다. 1차 실측의 claude 판이 정확히 그 모양이었다
# (바닥 입력창은 고정, 가운데 전사는 흐름 → `found 32 · cap 0`).
#
#   - 멈춘 화면(`03-tui.sh`·`vim -O`)은 꼬리가 통째로 맞아 0줄이 정직하게 나온다 → 상한이 안 문다
#   - 전부 흐르는 화면은 꼬리가 하나도 안 맞아 어림잡기로 가고, 알트 판은 `recent` 가 화면보다
#     짧아 결국 0줄이다 → 이것도 상한이 안 문다 (드라이런에서 확인)
#
# 그래서 **바닥 고정 + 가운데 스크롤**로 에이전트 TUI 를 흉내 낸다. 여기서 상한 0 이 문다.
printf '\033[?1049h\033[2J'
rows=$(tput lines 2>/dev/null || echo 39)
foot=$((rows - 3))
printf '\033[1;%dr' "$foot"
i=0
while [ $i -lt 3000 ]; do
  i=$((i + 1))
  printf '\033[%d;1H\033[K ALTSCROLL %04d ─ 흐르는 본문 · 한글 칸 맞춤\n' "$foot" "$i"
  printf '\033[%d;1H\033[K┌─ 고정 바닥 (입력창 흉내) ─────────────' "$((foot + 1))"
  printf '\033[%d;1H\033[K│ ALT FOOTER 고정 줄' "$((foot + 2))"
  sleep 0.1
done
printf '\033[r\033[?1049l'
