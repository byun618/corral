# ⑤ **움직이며 스크롤하는** 전체화면 TUI — 씨앗 상한이 실제로 무는 화면 (T5, 2회차 리뷰 G6).
#
# 왜 따로 필요한가: `03-tui.sh` 도 `vim -O` 도 알트스크린이지만 **화면이 멈춰 있다.** 멈춘
# 화면은 두 스냅샷의 꼬리가 맞아 `historyAbove` 가 0줄을 정직하게 돌려주고, 그러면 상한이
# 한 번도 안 물어 회귀 검사가 빈다 (1차 `scrollback-alt` 런의 `term.scrollback.capped` 0건).
#
# 여기서는 알트 판 안에서 **계속 새 줄을 흘려 스크롤**시킨다. 그러면 ① 두 스냅샷이 어긋나
# 꼬리 일치가 실패하고 ② `recent_unwrapped` 가 화면 행 수보다 많은 줄을 준다 —
# 어림잡기가 과거를 지어내려 드는 바로 그 조건이고, 거기서 상한 0 이 문다.
printf '\033[?1049h\033[2J\033[H'
i=0
while [ $i -lt 3000 ]; do
  i=$((i + 1))
  printf 'ALTSCROLL %04d ─ 움직이는 전체화면 TUI · 한글 칸 맞춤\n' "$i"
  sleep 0.2
done
printf '\033[?1049l'
