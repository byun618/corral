// M0 — 배선 확인. 판정 항목이 아니다. 앱이 뜨고, 버튼이 보이고, 행이 생기고 죽는지만 본다.
import { startApp, tidySession, sleep, until, firstWorkspaceId, herdrTruth, corralIds } from './lib.mjs'

await tidySession()
const app = await startApp({ name: 'm0-smoke' })
const workspaceId = await firstWorkspaceId(app)
console.log('workspace', workspaceId)
console.log('new-row button', JSON.stringify(await app.query(`[data-new-row="${workspaceId}"]`)))
console.log('click +', JSON.stringify(await app.click(`[data-new-row="${workspaceId}"]`)))
await sleep(600)
console.log('kinds', JSON.stringify(await app.query(`[data-kinds="${workspaceId}"] .btn-kind`)))
console.log('click shell', JSON.stringify(await app.click(`[data-launch-kind="${workspaceId}:shell"]`)))
const grown = await until(async () => (await herdrTruth()).tabs.length >= 2, { what: 'tab 2개' })
console.log('herdr grew', grown.ok, grown.ms)
await sleep(2500)
const state = await app.state()
console.log('corral', JSON.stringify(corralIds(state)))
console.log('herdr ', JSON.stringify(await herdrTruth()))
console.log('launches', JSON.stringify(state.lifecycle))
const tabId = state.workspaces[0].tabs.at(-1).tabId
console.log('close', JSON.stringify(await app.click(`[data-close-tab="${tabId}"]`)))
await sleep(2000)
console.log('after', JSON.stringify(corralIds(await app.state())), JSON.stringify(await herdrTruth()))
await app.shot('smoke')
await app.stop()
