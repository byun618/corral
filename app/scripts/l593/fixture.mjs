// 추적 중인데 패턴에 걸린 파일·공백/한글(NFC·NFD) 이름·심볼릭 링크(파일·폴더, 밖을 가리키는 것 포함). 밖 대상은 <ROOT>/outside.
// 사용: node scripts/l593/fixture.mjs <대상 폴더 /tmp/l593*/repo>   (이미 있으면 지우고 다시 만든다 — /tmp/l593 접두사만)
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const target = process.argv[2]
if (target === undefined || !/^\/tmp\/l593[^/]*\/repo$/.test(target)) throw new Error(`대상은 /tmp/l593*/repo 여야 한다: ${target}`)
fs.rmSync(target, { recursive: true, force: true })
const outside = path.join(path.dirname(target), 'outside')
fs.rmSync(outside, { recursive: true, force: true })
fs.mkdirSync(outside, { recursive: true })
fs.writeFileSync(path.join(outside, 'l593-secret.txt'), 'outside\n')
const write = (rel, content = `// ${rel}\n`) => {
  fs.mkdirSync(path.dirname(path.join(target, rel)), { recursive: true })
  fs.writeFileSync(path.join(target, rel), content)
}
const git = (...args) => execFileSync('git', ['-C', target, ...args])
fs.mkdirSync(target, { recursive: true })
execFileSync('git', ['init', '-q', '-b', 'main', target])
write('.gitignore', 'build/\n*.log\n!keep.log\nnode_modules/\nforced-ignored.txt\n')
write('.github/workflows/ci.yml', 'name: ci\n')
write('README.md', '# l593 fixture\n')
write('src/app.ts', 'export const app = 1\n')
write('src/deep/a/b/l593-target.ts', 'export const target = 1\n')
write('src/deep/a/b/l593-needle.md', '# needle\n')
write('docs/guide/l593-needle-guide.md', '# needle guide\n')
write('src/sub/.gitignore', 'local-only.txt\n')
write('src/sub/local-only.txt', 'local\n')
write('src/sub/kept.ts', 'export const kept = 1\n')
write('build/out.js', '// build\n')
write('debug.log', 'log\n')
write('keep.log', 'keep\n')
write('forced-ignored.txt', 'forced\n')
write('with space/file name.md', '# space\n')
write('한글/파일.md', '# 한글\n')
write('nfd/' + '노트'.normalize('NFD') + '.md', '# nfd\n')
write('excluded-by-info.txt', 'info\n')
write('node_modules/pkg/index.js', '// pkg\n')
fs.mkdirSync(path.join(target, '.git', 'info'), { recursive: true })
fs.writeFileSync(path.join(target, '.git', 'info', 'exclude'), 'excluded-by-info.txt\n')
fs.symlinkSync('src/app.ts', path.join(target, 'link-file'))
fs.symlinkSync('src', path.join(target, 'link-dir'))
fs.symlinkSync(outside, path.join(target, 'link-outside-dir'))
fs.symlinkSync(path.join(outside, 'l593-secret.txt'), path.join(target, 'link-outside-file'))
git('add', '.gitignore', '.github', 'README.md', 'src/app.ts', 'src/deep', 'docs', 'src/sub/.gitignore', 'src/sub/kept.ts', 'keep.log', 'with space', '한글', 'nfd', 'link-file', 'link-dir')
git('add', '-f', 'forced-ignored.txt')
git('-c', 'user.name=l593', '-c', 'user.email=l593@example.invalid', 'commit', '-q', '-m', 'fixture')
write('src/untracked-new.ts', 'export const fresh = 1\n')
